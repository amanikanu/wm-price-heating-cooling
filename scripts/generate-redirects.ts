/**
 * Generates /content/redirects.ts from the crawled legacy URL inventory
 * (content/legacy-urls.json) and the current route list.
 * Every legacy URL gets ONE 301 to a real 200 route — no chains.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { allPublicRoutes } from '../content/routes';

const root = process.cwd();
const legacy: string[] = JSON.parse(readFileSync(resolve(root, 'content/legacy-urls.json'), 'utf8'));
const built = new Set(allPublicRoutes());

const explicit: Record<string, string> = {
  '/request-estimate/': '/request-service/?type=Estimate',
  '/maintenance-membership-contact-form/': '/assurance-and-security-plans/',
  '/city/other/': '/service-area/',
  '/is-your-heating-system-ready-for-company-state-long-winter/': '/is-your-heating-system-ready-for-ohio-winter/',
  '/how-long-will-a-furnace-heat-pump-or-boiler-last-in-company-state-long/': '/how-long-will-a-furnace-heat-pump-or-boiler-last/',
};

const productRules: [RegExp, string][] = [
  [/oil-furnace/, '/residential/oil-furnaces/'],
  [/gas-furnace|furnace/, '/residential/furnaces/'],
  [/boiler/, '/residential/boilers/'],
  [/heat-pump|geothermal/, '/residential/heat-pumps/'],
  [/ductless/, '/residential/ductless-systems/'],
  [/zone/, '/residential/zone-control-systems/'],
  [/air-quality|filter|humidifier|purifier|uv-|scrubber|ventilator/, '/residential/indoor-air-quality/'],
  [/air-conditioner|air-conditioning/, '/residential/air-conditioning/'],
  [/coil|thermostat|fan-coil|packaged|air-handler/, '/products/accessories/'],
];

function targetFor(path: string): string {
  if (explicit[path]) return explicit[path];
  if (path.startsWith('/products/carrier/')) return '/products/carrier/';
  if (path.startsWith('/hvac-product')) {
    for (const [re, target] of productRules) if (re.test(path)) return target;
    return '/products/carrier/';
  }
  if (path.startsWith('/testimonial')) return '/reviews/';
  if (path.startsWith('/category/')) return '/news/';
  if (path.startsWith('/city/')) return '/service-area/';
  if (path.startsWith('/video')) return '/company/';
  return '/site-map/';
}

const redirects: { source: string; destination: string; permanent: true }[] = [];
for (const path of legacy) {
  if (built.has(path)) continue;
  if (path === '/request-estimate/') redirects.push({ source: path, destination: explicit[path], permanent: true });
  else redirects.push({ source: path, destination: targetFor(path), permanent: true });
}
// Explicit legacy slugs may not be in the sitemap inventory, so guarantee them.
for (const [source, destination] of Object.entries(explicit)) {
  if (built.has(source)) continue;
  if (!redirects.some((r) => r.source === source)) redirects.push({ source, destination, permanent: true });
}
redirects.sort((a, b) => a.source.localeCompare(b.source));

const out = `/**
 * GENERATED by scripts/generate-redirects.ts from content/legacy-urls.json.
 * PRD 16.8 / F18: one 301 from every changed legacy URL to a live 200 route.
 * Targets are all members of allPublicRoutes() — verified by npm run check:redirects.
 */
export type LegacyRedirect = { source: string; destination: string; permanent: true };

export const redirects: LegacyRedirect[] = ${JSON.stringify(redirects, null, 2)};

export const nextConfigRedirects = redirects.map(({ source, destination, permanent }) => ({
  source, destination, permanent,
}));
`;
writeFileSync(resolve(root, 'content/redirects.ts'), out, 'utf8');
console.log(`wrote ${redirects.length} redirects (${legacy.length} legacy URLs, ${built.size} built routes)`);
